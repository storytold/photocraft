//! Exposure as Adobe Camera Raw (process version 2012) applies it.
//!
//! Measured as a black box on the Camera Raw Filter of Photoshop 2026 (Camera Raw 18.6): a grey
//! ramp of all 256 levels went through the filter at every half stop from −5 to +5 and came
//! back exactly; no Adobe code or data was used.
//!
//! - Exposure is one global curve per slider value, the same on every image (a photograph and
//!   the ramp give the same curve to 0.1 %). It is not a gain: shadows move about 1.4 times the
//!   slider's stops, the highlights roll off into white, and down to about −1 white stays white.
//! - Colour: the curve acts on linear ProPhoto RGB with the hue kept, as for a DNG profile's
//!   tone curve: the largest and smallest channels go through the curve and the middle one keeps
//!   its place between them. On a photograph this leaves ΔE 0.4 against Photoshop, where a curve
//!   per channel or a luminance gain leave 0.7 and 4.
//! - Between measured values the rows are interpolated in log₂ of the level, across the grey
//!   levels linearly.

