/// The same for Adobe RGB (1998).
const ADOBE_TO_PROPHOTO: Mat = [[0.740_176, 0.113_207, 0.146_618], [0.137_555, 0.833_071, 0.029_374], [0.023_607, 0.073_788, 0.902_605]];
const PROPHOTO_TO_ADOBE: Mat = [[1.389_521, -0.169_320, -0.220_201], [-0.228_813, 1.231_73, -0.002_917], [-0.017_637, -0.096_265, 1.113_902]];

/// The primaries that go with a document encoding ([`Encoding`]): ProPhoto's gamma 1.8 is
/// ProPhoto, Adobe RGB's 563/256 Adobe RGB, everything else sRGB's. `None` for ProPhoto (no
/// conversion), else the matrices to linear ProPhoto and back.
pub(crate) fn primaries(enc: Encoding) -> Option<Primaries> {
    match enc.0 {
        g if (g - 1.8).abs() < 1e-3 => None,
        g if (g - 563.0 / 256.0).abs() < 1e-3 => Some((ADOBE_TO_PROPHOTO, PROPHOTO_TO_ADOBE)),
        _ => Some((SRGB_TO_PROPHOTO, PROPHOTO_TO_SRGB)),
    }
}

/// The Exposure curve at slider value `e` (stops, −5 … 5) as one row over grey levels 0, 1/64,
/// …, 1 (sRGB-encoded): the neighbouring measured rows interpolated in log₂ of the level.
pub(crate) fn row(e: f32) -> [f32; STEPS] {
    interpolate(&EXPOSURES, &CURVES, e)
}

/// The curve at slider value `x` from measured `rows` at the increasing values `at` (one of
/// them 0, the identity): the neighbouring rows interpolated in log₂ of the level; outside the
/// measured values the end row, and the identity for a value that is not a number.
pub(crate) fn interpolate(at: &[f32], rows: &[[f32; STEPS]], x: f32) -> [f32; STEPS] {
    let (Some(first), Some(last)) = (at.first(), at.last()) else {
        return std::array::from_fn(|j| j as f32 / (STEPS - 1) as f32);
    };
    let x = if x.is_finite() { x.clamp(*first, *last) } else { 0.0 };
    let i = at.windows(2).position(|w| x <= w[1]).unwrap_or(at.len().saturating_sub(2));
    let (Some(a), Some(b), Some(xa), Some(xb)) = (rows.get(i), rows.get(i + 1), at.get(i), at.get(i + 1)) else {
        return rows.first().copied().unwrap_or(std::array::from_fn(|j| j as f32 / (STEPS - 1) as f32));
    };
    let t = (x - xa) / (xb - xa);
    // A measured value is its row exactly (0 is the identity).
    if t <= 0.0 || t >= 1.0 {
        return if t <= 0.0 { *a } else { *b };
    }
    std::array::from_fn(|j| if a[j] > 1e-6 && b[j] > 1e-6 { (a[j].log2() * (1.0 - t) + b[j].log2() * t).exp2() } else { a[j] * (1.0 - t) + b[j] * t })
}

/// One `row` at linear level `v`, in linear light. Above 1 (float documents) the excess is kept
/// on top of the curve's white, as the other tone curves extend; below 0 the level stays.
pub(crate) fn curve(row: &[f32; STEPS], v: f32) -> f32 {
    if v <= 0.0 {
        return v;
    }
    if v >= 1.0 {
        return super::srgb_to_linear(row[STEPS - 1]) + (v - 1.0);
    }
    let p = super::linear_to_srgb(v) * (STEPS - 1) as f32;
    let j = (p as usize).min(STEPS - 2);
    let s = p - j as f32;
    super::srgb_to_linear(row[j] + (row[j + 1] - row[j]) * s)
}

/// The curve on one linear ProPhoto pixel with its hue kept: the largest and smallest channels
/// through the curve, the middle one at the same fraction of the way between them.
pub(crate) fn tone(c: [f32; 3], row: &[f32; STEPS]) -> [f32; 3] {
    let (mut hi, mut lo) = (0, 0);
    for k in 1..3 {
        if c[k] > c[hi] {
            hi = k;
        }
        if c[k] < c[lo] {
            lo = k;
        }
    }
    if hi == lo {
        return c.map(|v| curve(row, v));
    }
    let mid = 3 - hi - lo;
    let (fh, fl) = (curve(row, c[hi]), curve(row, c[lo]));
    let mut out = [0.0; 3];
    out[hi] = fh;
    out[lo] = fl;
    out[mid] = fl + (fh - fl) * (c[mid] - c[lo]) / (c[hi] - c[lo]);
    out
}

/// A curve `row` on one straight pixel encoded with `enc`; `m` from [`primaries`].
pub(crate) fn pixel(mut q: [f32; 4], row: &[f32; STEPS], enc: Encoding, m: Option<&Primaries>) -> [f32; 4] {
    let lin = [0, 1, 2].map(|c| enc.decode(q[c]));
    let out = match m {
        Some((to, from)) => mat(from, tone(mat(to, lin), row)),
        None => tone(lin, row),
    };
    for c in 0..3 {
        q[c] = enc.encode(out[c]);
    }
    q
}

/// Applies a curve `row` (Exposure's or Contrast's) to straight RGBA pixels (`width` per row)
/// encoded with `enc`.
pub(crate) fn apply(px: &mut [[f32; 4]], width: usize, row: &[f32; STEPS], enc: Encoding) {
    let m = primaries(enc);
    par_rows(px, width, 1, |_, line| {
        for q in line.iter_mut() {
            *q = pixel(*q, row, enc, m.as_ref());
        }
    });
}

pub(crate) fn mat(m: &Mat, v: [f32; 3]) -> [f32; 3] {
    m.map(|r| r[0] * v[0] + r[1] * v[1] + r[2] * v[2])
}

#[cfg(test)]
mod tests {
    use super::*;

    fn grey(e: f32, level: f32) -> f32 {
        super::super::linear_to_srgb(curve(&row(e), super::super::srgb_to_linear(level / 255.0))) * 255.0
    }

    #[test]
    fn grey_levels_match_photoshop() {
        // Photoshop 2026 on the 256-level ramp (sRGB levels in, sRGB levels out).
        for (e, level, ps) in [(1.0, 128.0, 180.7), (-1.0, 128.0, 82.6), (2.0, 64.0, 152.9), (-2.0, 224.0, 127.4), (0.5, 32.0, 42.4)] {
            let ours = grey(e, level);
            assert!((ours - ps).abs() < 1.0, "Exposure {e} at {level}: {ours}, Photoshop {ps}");
        }
        // Down to −1 white stays white; at −2 it drops to about 0.56 linear.
        assert!((grey(-1.0, 255.0) - 255.0).abs() < 0.5);
        assert!((grey(-2.0, 255.0) - 197.5).abs() < 1.0);
    }

    #[test]
    fn rows_interpolate_and_clamp() {
        assert_eq!(row(0.0), std::array::from_fn(|j| j as f32 / (STEPS - 1) as f32));
        assert_eq!(row(9.0), row(5.0));
        assert_eq!(row(f32::NAN), row(0.0));
        let (a, b, m) = (grey(1.0, 100.0), grey(1.5, 100.0), grey(1.25, 100.0));
        assert!(a < m && m < b, "{a} {m} {b}");
    }

    #[test]
    fn hue_is_kept() {
        let r = row(1.0);
        let c = [0.30, 0.20, 0.05];
        let o = tone(c, &r);
        assert!(o[0] > c[0] && o[0] > o[1] && o[1] > o[2]);
        let frac = |v: [f32; 3]| (v[1] - v[2]) / (v[0] - v[2]);
        assert!((frac(o) - frac(c)).abs() < 1e-5);
        // Greys stay grey and float levels above 1 keep going.
        assert_eq!(tone([0.4; 3], &r), [curve(&r, 0.4); 3]);
        assert!((curve(&r, 2.0) - 2.0).abs() < 1e-3);
    }
}
