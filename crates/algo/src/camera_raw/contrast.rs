/// Contrast at slider value `c` (−100 … 100) as a row (see [`row`]), adapted to the image's
/// `tones` when known. Measured on Photoshop 2026: the curve is the same S on every image, but
/// where it crosses and how far it moves the darks and lights depends on the image (a bright
/// render crosses near L* 70, a dark aerial photograph near 45). Mean |ΔL*| on photographs left
/// out of the fit, one at a time: 0.16 (−25), 0.29 (−50), 0.51 (−100), 0.19 (+25), 0.37 (+50),
/// 0.79 (+100); the fixed curves of the ramp: 0.34, 0.64, 1.30, 0.37, 0.71, 1.48.
pub(crate) fn adaptive_row(c: f32, tones: Option<Tones>) -> [f32; STEPS] {
    let Some([p1, p50, p99, mean]) = tones.filter(|t| t.iter().all(|v| v.is_finite())) else {
        return row(c);
    };
    if !c.is_finite() || c == 0.0 {
        return row(0.0);
    }
    let lstar = |u: f32| super::lstar(u.exp2());
    let (lk, l1, l50, l99) = (lstar(mean), lstar(p1), lstar(p50), lstar(p99));
    let feats = [1.0, (lk - 45.0) / 20.0, (l99 - 90.0) / 10.0, (l1 - 5.0) / 10.0, (l50 - 45.0) / 20.0];
    let fitted = |t: &[[f32; ADAPT_KNOTS]; 5], l: f32| {
        let x = ((l + 60.0) / 5.0).clamp(0.0, (ADAPT_KNOTS - 1) as f32);
        let i = (x as usize).min(ADAPT_KNOTS - 2);
        let s = x - i as f32;
        t.iter().zip(feats).map(|(r, f)| (r[i] + (r[i + 1] - r[i]) * s) * f).sum::<f32>()
    };
    // The fitted values on this side, from none at 0; between them the move interpolates.
    let side: [usize; 3] = if c < 0.0 { [0, 1, 2] } else { [3, 4, 5] };
    let a = c.abs().min(100.0);
    let mv = |l: f32| {
        let mut prev = (0.0f32, 0.0f32);
        for &k in &side {
            let at = ADAPT_AT[k].abs();
            let here = fitted(&ADAPT[k], l);
            if a <= at {
                return prev.1 + (here - prev.1) * (a - prev.0) / (at - prev.0);
            }
            prev = (at, here);
        }
        prev.1
    };
    let mut out: [f32; STEPS] = std::array::from_fn(|k| {
        let y = super::srgb_to_linear(k as f32 / (STEPS - 1) as f32);
        let l = super::lstar(y);
        let l2 = (l + mv(l)).clamp(0.0, 100.0);
        super::linear_to_srgb(super::lstar_inverse(l2))
    });
    // Black stays black, and the curve never falls.
    out[0] = 0.0;
    for k in 1..STEPS {
        out[k] = out[k].max(out[k - 1]).min(1.0);
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn grey(c: f32, level: f32) -> f32 {
        let lin = super::super::exposure::curve(&row(c), super::super::srgb_to_linear(level / 255.0));
        super::super::linear_to_srgb(lin) * 255.0
    }

    #[test]
    fn grey_levels_match_photoshop() {
        // Photoshop 2026 on the 256-level ramp (sRGB levels in and out).
        for (c, level, ps) in
            [(100.0, 48.0, 20.7), (100.0, 208.0, 229.1), (-100.0, 48.0, 72.4), (-100.0, 208.0, 188.1), (50.0, 96.0, 84.7), (-25.0, 160.0, 157.1)]
        {
            let ours = grey(c, level);
            assert!((ours - ps).abs() < 1.0, "Contrast {c} at {level}: {ours}, Photoshop {ps}");
        }
        // Black and white stay.
        assert!(grey(100.0, 0.0) < 0.5 && grey(-100.0, 255.0) > 254.5);
    }

    #[test]
    fn rows_interpolate_and_clamp() {
        assert_eq!(row(0.0), std::array::from_fn(|j| j as f32 / (STEPS - 1) as f32));
        assert_eq!(row(300.0), row(100.0));
        assert_eq!(row(f32::NAN), row(0.0));
        let (a, m, b) = (grey(25.0, 60.0), grey(37.5, 60.0), grey(50.0, 60.0));
        assert!(b < m && m < a, "{a} {m} {b}");
    }

    /// The level (0 … 255) where an adaptive row crosses the identity, searched from the darks.
    fn crossing(r: &[f32; STEPS]) -> f32 {
        let lv = |k: usize| k as f32 / (STEPS - 1) as f32;
        (8..STEPS - 4).find(|&k| r[k] >= lv(k) && r[k - 1] < lv(k - 1)).map_or(f32::NAN, |k| lv(k) * 255.0)
    }

    #[test]
    fn adaptive_rows_follow_the_image() {
        // A bright render (mean −1.6 stops) and a dark aerial photograph (mean −4.6): Photoshop's
        // +100 crosses near L* 70 (level 175) on the first and near L* 45 (level 110) on the second.
        let bright = adaptive_row(100.0, Some([-6.1, -0.8, -0.3, -1.6]));
        let dark = adaptive_row(100.0, Some([-8.1, -5.3, 0.0, -4.6]));
        let (cb, cd) = (crossing(&bright), crossing(&dark));
        assert!(cb > cd + 25.0 && cd > 70.0 && cb < 210.0, "{cb} {cd}");
        // Every row starts at black and never falls; −100 lifts the darks.
        for t in [Some([-6.1, -0.8, -0.3, -1.6]), Some([-8.1, -5.3, 0.0, -4.6])] {
            for c in [-100.0, -60.0, -25.0, 10.0, 75.0, 100.0] {
                let r = adaptive_row(c, t);
                assert!(r[0] == 0.0 && r.windows(2).all(|p| p[1] >= p[0]) && r[STEPS - 1] <= 1.0, "{c} {t:?}");
            }
            assert!(adaptive_row(-100.0, t)[16] > 16.0 / 64.0);
        }
        // Up to +25 the move grows with the slider.
        let m = |c: f32| adaptive_row(c, Some([-8.1, -5.3, 0.0, -4.6]))[48] - 0.75;
        assert!(m(10.0) > 0.0 && m(10.0) < m(25.0), "{} {}", m(10.0), m(25.0));
        // Without tones, or with broken ones, the fixed curves; 0 is the identity.
        assert_eq!(adaptive_row(50.0, None), row(50.0));
        assert_eq!(adaptive_row(50.0, Some([f32::NAN, -2.0, 0.0, -2.0])), row(50.0));
        assert_eq!(adaptive_row(0.0, Some([-6.0, -2.0, 0.0, -2.0])), row(0.0));
        assert!(adaptive_row(f32::NAN, Some([-6.0, -2.0, 0.0, -2.0])).iter().all(|v| v.is_finite()));
    }
}
