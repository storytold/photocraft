//! Highlights and Shadows as multi-scale moves of the log2 luminance, fitted by observation.
//!
//! Measured as a black box on Photoshop 2026's Camera Raw Filter (Camera Raw 18.6): no Adobe
//! code or data was used. What the measurements show:
//!
//! - A uniform image does not change, at any level: both sliders work on contrast only.
//! - The move is close to a curve of the level within each image, but which levels move depends
//!   on the picture. Highlights lowers a large bright region (a sky, a beach) as a block, its
//!   own detail kept, and the less of the picture it covers and the darker its surroundings, the
//!   further it goes; fine detail (stripes a few pixels wide) moves much less than the same
//!   levels in large areas. Shadows lifts most around L* 15–35 and more where a dark area is
//!   large and darker than its surroundings.
//!
//! The model: on a copy at most [`SIDE`] pixels across, a pixel at log2 luminance `u` moves by
//! `A · Σ_j b_j(t) · (k0_j + Σ_s k+_sj · max(D_s, 0) + k−_sj · min(D_s, 0))` stops, where
//! `t = (u − p1) / span` is its place in the image range (1st to 99th percentile), `b_j` are
//! linear interpolation weights over knots at t = −0.1, 0, …, 1.2, `D_s = (u − G_s u) / span`
//! is how far it lies above its surroundings at five scales (Gaussian blurs of 1 % to 100 % of
//! the long side), and `A = span · (span / 6)^(γ − 1)` grows a little faster than the range.
//! The coefficients were fitted by least squares (with a smoothness penalty along `t`) to
//! Photoshop's results at −100, −50, +50 and +100 on 34 photographs and renders; other slider
//! values interpolate between those moves. The caller brings the move to full size.
//!
//! Mean |ΔL*| against Photoshop on 14 photographs left out of the fit, one at a time, at −100,
//! −50, +50, +100 (the previous curves of the range only in brackets):
//! Highlights 0.93, 0.44, 0.57, 1.16 (1.96, 1.06, 1.03, 1.39);
//! Shadows 1.09, 0.63, 0.75, 1.63 (2.30, …, 3.47).

use super::Plane;

/// The model runs on a copy at most this many pixels across.
pub(super) const SIDE: usize = 384;
/// Knots of `t`: −0.1 + 0.1·j.
const KNOTS: usize = 14;
const KNOT0: f32 = -0.1;
const KNOT_STEP: f32 = 0.1;
/// Gaussian sigmas of the surroundings, as a share of the long side.
const SCALES: [f32; 5] = [0.01, 0.03, 0.1, 0.3, 1.0];
/// A move never exceeds this many stops (a guard for images unlike any measured).
const MAX_MOVE: f32 = 6.0;

/// The fitted coefficients for one slider value: row 0 is `k0`, then `k+` and `k−` per scale.
struct Table {
    gam: f32,
    k: [[f32; KNOTS]; 1 + 2 * SCALES.len()],
}

/// One slider's tables at −50, −100, +50 and +100.
pub(super) struct Tables {
    down_50: Table,
    down_100: Table,
    up_50: Table,
    up_100: Table,
}

/// The move in stops of every pixel of `u` (log2 luminance, at most [`SIDE`] across) for the
/// slider of `tables` at `amount` (−1 … 1).
pub(super) fn moves(u: &Plane, amount: f32, tables: &Tables) -> Vec<f32> {
    if amount == 0.0 || !amount.is_finite() || u.v.is_empty() {
        return vec![0.0; u.v.len()];
    }
    let a = amount.clamp(-1.0, 1.0);
    let (half, full) = if a < 0.0 { (&tables.down_50, &tables.down_100) } else { (&tables.up_50, &tables.up_100) };
    let m = a.abs();
    let ctx = Context::new(u);
    let at_half = ctx.apply(half);
    if m <= 0.5 {
        let f = m / 0.5;
        return at_half.into_iter().map(|d| d * f).collect();
    }
    let f = (m - 0.5) / 0.5;
    ctx.apply(full).into_iter().zip(at_half).map(|(b, h)| h + (b - h) * f).collect()
}

/// What the move needs of an image: its range and its surroundings at each scale.
struct Context<'a> {
    u: &'a Plane,
    lo: f32,
    span: f32,
    blurs: Vec<Vec<f32>>,
}

impl<'a> Context<'a> {
    fn new(u: &'a Plane) -> Self {
        let (lo, hi) = range(u);
        let long = u.w.max(u.h) as f32;
        let blurs = SCALES.iter().map(|s| gauss_inside(&u.v, u.w, u.h, s * long)).collect();
        Context { u, lo, span: hi - lo, blurs }
    }

    fn apply(&self, t: &Table) -> Vec<f32> {
        // No range, no move (a uniform image is unchanged).
        if self.span.is_nan() || self.span <= 1e-4 {
            return vec![0.0; self.u.v.len()];
        }
        let amp = self.span * (self.span / 6.0).powf(t.gam - 1.0);
        let limit = MAX_MOVE.min(self.span);
        self.u
            .v
            .iter()
            .enumerate()
            .map(|(i, &u)| {
                let x = (((u - self.lo) / self.span - KNOT0) / KNOT_STEP).clamp(0.0, (KNOTS - 1) as f32);
                let j = (x as usize).min(KNOTS - 2);
                let s = x - j as f32;
                let row = |r: usize| t.k[r][j] * (1.0 - s) + t.k[r][j + 1] * s;
                let mut v = row(0);
                for (n, b) in self.blurs.iter().enumerate() {
                    let d = (u - b.get(i).copied().unwrap_or(u)) / self.span;
                    v += row(1 + 2 * n) * d.max(0.0) + row(2 + 2 * n) * d.min(0.0);
                }
                (amp * v).clamp(-limit, limit)
            })
            .collect()
    }
}

/// The `q` quantile (0 … 1) of `v`, interpolated between ranks.
fn quantile_lerp(v: &[f32], q: f32) -> f32 {
    if v.is_empty() {
        return 0.0;
    }
    let mut s = v.to_vec();
    s.sort_by(f32::total_cmp);
    let x = (s.len() - 1) as f32 * q.clamp(0.0, 1.0);
    let i = (x as usize).min(s.len() - 1);
    let j = (i + 1).min(s.len() - 1);
    s[i] + (s[j] - s[i]) * (x - i as f32)
}

/// 1st and 99th percentiles of `u` averaged over blocks so that at most 256 remain across
/// (whole blocks only).
fn range(u: &Plane) -> (f32, f32) {
    let f = u.w.max(u.h).div_ceil(256).max(1);
    let (bw, bh) = (u.w / f, u.h / f);
    if bw == 0 || bh == 0 {
        return (0.0, 0.0);
    }
    let n = (f * f) as f32;
    let cells: Vec<f32> = (0..bw * bh)
        .map(|c| {
            let (x0, y0) = ((c % bw) * f, (c / bw) * f);
            (y0..y0 + f).flat_map(|y| (x0..x0 + f).map(move |x| y * u.w + x)).map(|i| u.v[i]).sum::<f32>() / n
        })
        .collect();
    (quantile_lerp(&cells, 0.01), quantile_lerp(&cells, 0.99))
}

/// A Gaussian of `sigma` pixels as three box passes, each box averaging only the part of its
/// window inside the image (so the edges do not weigh more than the inside).
fn gauss_inside(v: &[f32], w: usize, h: usize, sigma: f32) -> Vec<f32> {
    if sigma < 0.3 {
        return v.to_vec();
    }
    let mut out = v.to_vec();
    for r in crate::fxutil::gauss_box_radii(sigma) {
        out = box_inside(&out, w, h, r);
    }
    out
}

/// Box mean of radius `r` over the window clipped to the image: rows, then columns.
fn box_inside(v: &[f32], w: usize, h: usize, r: usize) -> Vec<f32> {
    if r == 0 || w == 0 || h == 0 || v.len() != w * h {
        return v.to_vec();
    }
    let pass = |src: &[f32], n: usize, lines: usize, at: &dyn Fn(usize, usize) -> usize| -> Vec<f32> {
        let mut out = vec![0.0f32; src.len()];
        let mut sum = vec![0.0f64; n + 1];
        for line in 0..lines {
            for k in 0..n {
                sum[k + 1] = sum[k] + f64::from(src[at(line, k)]);
            }
            for k in 0..n {
                let (a, b) = (k.saturating_sub(r), (k + r + 1).min(n));
                out[at(line, k)] = ((sum[b] - sum[a]) / (b - a) as f64) as f32;
            }
        }
        out
    };
    let rows = pass(v, w, h, &|y, x| y * w + x);
    pass(&rows, h, w, &|x, y| y * w + x)
}

