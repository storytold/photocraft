use super::sponge_desaturate_tests::check_reference;

#[test]
fn saturate_matches_measured_single_dabs() {
    // One 40 px hard round dab at 25% spacing, measured in #12973.
    check_reference(
        true,
        true,
        0.5,
        [[211, 40, 40], [40, 172, 62], [40, 61, 211], [227, 169, 135], [235, 204, 38], [97, 52, 30], [176, 199, 235], [133, 62, 204], [255, 0, 0]],
    );
    check_reference(
        true,
        true,
        1.0,
        [[222, 39, 39], [39, 184, 64], [39, 62, 222], [234, 169, 130], [240, 207, 36], [105, 55, 30], [171, 199, 240], [138, 60, 217], [255, 0, 0]],
    );
    check_reference(
        true,
        false,
        0.5,
        [[222, 31, 31], [25, 169, 49], [34, 58, 225], [228, 168, 132], [238, 202, 11], [96, 48, 24], [177, 201, 237], [134, 57, 210], [255, 1, 1]],
    );
    check_reference(
        true,
        false,
        1.0,
        [[244, 21, 21], [11, 178, 39], [28, 56, 251], [235, 166, 124], [240, 202, 1], [102, 46, 18], [173, 201, 243], [140, 51, 229], [255, 1, 1]],
    );
}
