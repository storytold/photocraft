//! Optional craft-fonts build input (https://github.com/storytold/craft-fonts, recipe from its
//! `docs/integration.md`).
//!
//! With `CRAFT_FONTS_DIR=<craft-fonts checkout>`, every font in its `fonts/manifest.txt` is
//! embedded and exposed as `photocraft_text::CRAFT_FONTS`; unset, `CRAFT_FONTS` is empty and the
//! build is exactly as before (an empty value counts as unset). Use an absolute path: build
//! scripts run in the crate's directory, so a relative one resolves from `crates/text`. A bad
//! checkout is a warning, or an error with `CRAFT_FONTS_REQUIRED=1` (release builds).
//!
//! PhotoCraft difference from the recipe: the web build (wasm32) embeds nothing. The wasm must
//! stay under the 24 MiB gate in `packaging/web/package.sh` (#237; Cloudflare's per-file cap is
//! 25 MiB). Measured 2026-10-06 (`trunk build --release`): 24,190,076 bytes
//! without craft-fonts, 28,867,488 with only the UI face (BIZ UDPGothic Regular) embedded, over
//! the 25,165,824-byte gate. The web build loads fonts served next to the wasm instead, on
//! demand (`fonts/manifest.txt`, see `served.rs` and packaging/web/README.md › Fonts).
//!
//! Also deflates the bundled UI fonts (`assets/fonts/*.ttf`, `fonts::BUNDLED`) into
//! `OUT_DIR/fonts/<file>.deflate`: 0.73 MB of binary instead of 1.5 MB, for the same size gate.
//!
//! And generates the font menu's per-script ordering tables (`OUT_DIR/collation.rs`, read by
//! `collate.rs`) from `encoding_rs`'s character sets: GB2312's pinyin order for Simplified
//! Chinese, Big5's stroke order, JIS X 0208's gojūon order and KS X 1001's.
use std::fmt::Write as _;
use std::path::PathBuf;

fn main() {
    println!("cargo::rerun-if-env-changed=CRAFT_FONTS_DIR");
    println!("cargo::rerun-if-env-changed=CRAFT_FONTS_REQUIRED");
    let wasm = std::env::var("CARGO_CFG_TARGET_ARCH").is_ok_and(|a| a == "wasm32");
    let mut src = String::from("pub static CRAFT_FONTS: &[CraftFont] = &[\n");
    if let Some(dir) = std::env::var_os("CRAFT_FONTS_DIR").filter(|d| !d.is_empty() && !wasm).map(PathBuf::from) {
        match craft_fonts(&dir) {
            Ok(entries) => src.push_str(&entries),
            Err(e) if std::env::var_os("CRAFT_FONTS_REQUIRED").is_some() => {
                println!("cargo::error=CRAFT_FONTS_DIR={}: {e}", dir.display());
            }
            Err(e) => println!("cargo::warning=building without craft-fonts: CRAFT_FONTS_DIR={}: {e}", dir.display()),
        }
    }
    src.push_str("];\n");
    let out = PathBuf::from(std::env::var_os("OUT_DIR").unwrap_or_default()).join("craft_fonts.rs");
    if let Err(e) = std::fs::write(&out, src) {
        println!("cargo::error=writing {}: {e}", out.display());
    }
    deflate_bundled_fonts();
    collation_tables();
}

/// The font menu's ordering tables (`collate.rs`): each writing system's standard character set,
/// its characters in the order the set lists them — GB2312's pinyin rows for Simplified Chinese,
/// Big5's stroke order, JIS X 0208's gojūon order and KS X 1001's — written to
/// `OUT_DIR/collation.rs` as characters sorted by code point, with each one's rank in that order
/// (a binary search at run time, no table of its own in memory).
///
/// `encoding_rs` encodes a character to the bytes its set gives it, and each set orders its
/// characters by those bytes, so sorting the encoded bytes sorts by the set's order. Only the
/// standard sets' own characters are listed; a character outside them sorts by code point at run
/// time (`collate.rs`).
fn collation_tables() {
    let out = PathBuf::from(std::env::var_os("OUT_DIR").unwrap_or_default()).join("collation.rs");
    let mut src = String::from("// Generated by build.rs from encoding_rs: each writing system's standard set, characters by code point, ranks in the set's order.
");
    // GB2312 is the A1A1–F7FE part of GBK; GBK's own extensions are not in its order.
    write_set(&mut src, "HANS", encoding_rs::GBK, |b| matches!(b, [0xA1..=0xF7, 0xA1..=0xFE]));
    write_set(&mut src, "HANT", encoding_rs::BIG5, |b| matches!(b, [0xA1..=0xF9, 0x40..=0x7E | 0xA1..=0xFE]));
    // Shift_JIS's two-byte codes are JIS X 0208, in ku/ten order (its one-byte half-width
    // katakana are left out: they fold onto the full-width kana when sorting).
    write_set(&mut src, "JPAN", encoding_rs::SHIFT_JIS, |b| b.len() == 2);
    write_set(&mut src, "KORE", encoding_rs::EUC_KR, |b| matches!(b, [0xA1..=0xFE, 0xA1..=0xFE]));
    if let Err(e) = std::fs::write(&out, src) {
        println!("cargo::error=writing {}: {e}", out.display());
    }
}

/// One table: every CJK character `encoding` maps to a two-byte code `in_set` takes, ordered by
/// those codes (the set's own order), written as the characters by code point and their ranks.
fn write_set(src: &mut String, name: &str, encoding: &'static encoding_rs::Encoding, in_set: impl Fn(&[u8]) -> bool) {
    let mut ordered: Vec<(Vec<u8>, char)> = Vec::new();
    for u in 0x1100u32..=0xFFFF {
        let Some(c) = char::from_u32(u) else { continue };
        if !is_cjk(c) {
            continue;
        }
        let mut buf = [0u8; 4];
        let (bytes, _, failed) = encoding.encode(c.encode_utf8(&mut buf));
        if failed || !in_set(bytes.as_ref()) {
            continue;
        }
        ordered.push((bytes.into_owned(), c));
    }
    ordered.sort();
    if ordered.len() > usize::from(u16::MAX) {
        println!("cargo::error={name}: {} characters, more than a u16 rank holds", ordered.len());
        return;
    }
    // Characters by code point, each with its rank in the set's order.
    let mut by_char: Vec<(char, u16)> = ordered.iter().enumerate().map(|(rank, (_, c))| (*c, rank as u16)).collect();
    by_char.sort_by_key(|(c, _)| *c as u32);
    let chars = by_char.iter().map(|(c, _)| format!("'\\u{{{:x}}}'", *c as u32)).collect::<Vec<_>>().join(",");
    let ranks = by_char.iter().map(|(_, r)| r.to_string()).collect::<Vec<_>>().join(",");
    let n = by_char.len();
    let _ = writeln!(src, "pub static {name}_CHARS: [char; {n}] = [{chars}];");
    let _ = writeln!(src, "pub static {name}_RANKS: [u16; {n}] = [{ranks}];");
}

/// The characters a font menu can list in these scripts: kana, Hangul, Han, Bopomofo, CJK
/// punctuation and full-width forms (as `photocraft_text::cjk::classify` has them).
fn is_cjk(c: char) -> bool {
    matches!(c as u32, 0x1100..=0x11FF | 0x2E80..=0x303F | 0x3040..=0x31FF
        | 0x3200..=0x33FF | 0x3400..=0x4DBF | 0x4E00..=0x9FFF | 0xA960..=0xA97F | 0xAC00..=0xD7FF
        | 0xF900..=0xFAFF | 0xFE30..=0xFE4F | 0xFF65..=0xFF9F | 0x1B000..=0x1B16F)
}

/// Deflate the bundled fonts into `OUT_DIR/fonts/` (`fonts::BUNDLED` includes them).
fn deflate_bundled_fonts() {
    use std::io::Write as _;
    let src = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../assets/fonts");
    let out = PathBuf::from(std::env::var_os("OUT_DIR").unwrap_or_default()).join("fonts");
    let result = (|| -> std::io::Result<()> {
        std::fs::create_dir_all(&out)?;
        for name in ["Inter-Regular.ttf", "Inter-Medium.ttf", "Inter-SemiBold.ttf", "JetBrainsMono-Regular.ttf"] {
            let path = src.join(name);
            println!("cargo::rerun-if-changed={}", path.display());
            let mut z = flate2::write::DeflateEncoder::new(Vec::new(), flate2::Compression::best());
            z.write_all(&std::fs::read(&path)?)?;
            std::fs::write(out.join(format!("{name}.deflate")), z.finish()?)?;
        }
        Ok(())
    })();
    if let Err(e) = result {
        println!("cargo::error=deflating the bundled fonts in {}: {e}", src.display());
    }
}

/// One `CraftFont { .. }` initialiser per manifest line.
fn craft_fonts(dir: &std::path::Path) -> Result<String, String> {
    let manifest = dir.join("fonts/manifest.txt");
    println!("cargo::rerun-if-changed={}", manifest.display());
    let text = std::fs::read_to_string(&manifest).map_err(|e| format!("{}: {e}", manifest.display()))?;
    let mut out = String::new();
    for line in text.lines().map(str::trim).filter(|l| !l.is_empty() && !l.starts_with('#')) {
        let f: Vec<&str> = line.split(" | ").map(str::trim).collect();
        let [family, style, file, scripts, ..] = f.as_slice() else {
            return Err(format!("malformed manifest line: {line}"));
        };
        let path = dir.join(file).canonicalize().map_err(|e| format!("{file}: {e}"))?;
        println!("cargo::rerun-if-changed={}", path.display());
        let scripts: Vec<String> = scripts.split(',').map(|s| format!("{:?}", s.trim())).collect();
        let _ = writeln!(
            out,
            "    CraftFont {{ family: {family:?}, style: {style:?}, scripts: &[{}], bytes: include_bytes!({:?}) }},",
            scripts.join(", "),
            path.display().to_string(),
        );
    }
    Ok(out)
}
